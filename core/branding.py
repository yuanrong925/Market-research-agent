"""
Branding — 为引擎打上垂直化烙印

# 设计目的
在 core/ 引擎层面不包含任何业务逻辑，但通过 branding 模块
向项目注入【市场调研专属】的垂直烙印，用于：
- 日志输出显示项目身份
- LLM 的 system prompt 注入领域标识
- 前端展示项目品牌

# 可替换性
当复用 core/ 到其他垂直领域（如法律咨询、医疗诊断）时，只需：
1. 修改 branding.py 中的领域名称和描述
2. 在 business/ 下创建新的业务插件目录
"""

from typing import Dict

# ============================================================
#  垂直领域烙印配置
# ============================================================

BRANDING_CONFIG: Dict[str, str] = {
    "app_name": "【市场调研专属】智能市场调研系统",
    "app_short_name": "Market Research Agent",
    "domain": "市场调研",
    "domain_en": "Market Research",
    "description": "专业市场调研、行业分析、竞品分析的智能研究助手",
    "version": "1.0.0",
    "slogan": "深度洞察，数据驱动 — 您的专属市场调研专家",
}

# ============================================================
#  System Prompt 注入（供 LLM 调用时使用）
# ============================================================

DOMAIN_SYSTEM_PROMPT = """你是一个专业的【市场调研】智能助手。

你的核心能力：
1. 市场调研：行业规模、市场趋势、竞争格局分析
2. 行业分析：产业链结构、商业模式、盈利模式
3. 竞品分析：产品对比、市场份额、战略定位
4. 用户研究：用户画像、需求洞察、行为分析
5. 数据驱动：基于事实和数据的分析结论

回答原则：
- 始终基于提供的材料和分析结果
- 使用专业、客观、中立的语言
- 保持市场调研报告的专业风格
- 数据标注来源，确保可追溯性
- 分析有深度，避免泛泛而谈"""


def get_branding_info() -> Dict[str, str]:
    """获取品牌信息（用于日志、前端展示）"""
    return dict(BRANDING_CONFIG)


def get_domain_system_prompt() -> str:
    """获取领域 system prompt（用于 LLM 初始化）"""
    return DOMAIN_SYSTEM_PROMPT